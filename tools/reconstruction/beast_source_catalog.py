"""Extract the complete current PET source declaration catalog, statically.

No native execution, instance grant, SQLite import, test or gameplay formula.
Generated keys/row identities can qualify custody, never generate beast stats.
"""
import json

from .archive_inputs import ArchivedInputs, SERVER
from .beast_panel_contract import section_rows

SOURCE='70a4e7dd1a1f66d7a70f5c5e97c77ef4063904cc473292758c5abd2da7bd8731'
DECODED='75c3c37947a64b0917fbf8e546884d9bf893fe6a606d3e2b8f3b1857966b1815'


def main():
    original='artifacts/capture_work/host-20260918-1430/client/Data2/Patch/Comm/gamedata.csvZ'
    archive=ArchivedInputs()
    try:
        raw=archive.read(original)
    finally:
        archive.close()
    source=section_rows('Data2/Patch/Comm/gamedata.csvZ',b'PET',None,compressed=raw,path_label=original)
    if source['compressed_sha256']!=SOURCE or source['decoded_sha256']!=DECODED:
        raise ValueError('Current PET source identity changed')
    rows=source['rows']
    if source['section']['declared_records']!=147 or len(rows)!=147:
        raise ValueError('Source PET section is incomplete')
    if len({row['id'] for row in rows})!=147:
        raise ValueError('Source PET keys alias')
    current=section_rows('Data2/Patch/Comm/gamedata.csvZ',b'PET',None)
    if [(r['id'],r['raw_hex']) for r in current['rows']]!=[(r['id'],r['raw_hex']) for r in rows]:
        raise ValueError('Current PET declarations differ from native source; keep original pins and recover the changed field authority')
    source['current_asset']={
        'path':current['path'],'compressed_sha256':current['compressed_sha256'],
        'decoded_sha256':current['decoded_sha256'],'section':current['section'],
        'scope':'all147 ordered PET row bytes match native; complete file differs and is not relabeled original',
        'client_acceptance':False}
    for index,row in enumerate(rows):
        fields=bytes.fromhex(row['raw_hex']).split(b',')
        row['source_record_index']=index
        row['resource_key']=fields[2].decode('ascii')
        row['raw_columns_hex']=[value.hex() for value in fields]
        # Native59420 class5 branch5970D calls51B50(27), which delegates
        # to zero-based51B60 and decimal51BA0, then stores AL at+11C.
        # B9267 tests that BYTE: zero selects level/EXP, nonzero packed date.
        row['tooltip_date_flag_byte']=int(fields[27])&0xff
    source['native_section_selector']=5
    source['native_section_binding']='mapped149c1b45... tag pointer table RVA1897EC entry5 ->PET; caller59301 to59420'
    source['tooltip_branch_binding']='class5 parser5970D source column27 decimal lowBYTE -> definition11C; B9267 zero: classic level/EXP, nonzero: packed date. No duration/expiry policy inferred.'
    source['authority']='SOURCE_DECLARATIONS_ONLY; not parsed396-byte objects, player instance stats, growth, eligibility or acquisition rules'
    output=SERVER/'artifacts/integration/packet-connections-20261006/beast-pet-source-catalog.json'
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(json.dumps(source,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    header='''#pragma once
#include <array>
#include <cstdint>
#include <string_view>

namespace god2 {
// Generated by tools/reconstruction/beast_source_catalog.py from ALL current
// PET declarations. Native tag selector5; independent from COM32/NCP34.
// Key/row qualification only. These rows do not generate instance snapshots,
// growth, food effects, actor appearance or a native59420 parsed object.
struct NativeBeastSourceCatalog {
    static constexpr std::string_view source_sha256="'''+SOURCE+'''";
    static constexpr std::string_view decoded_sha256="'''+DECODED+'''";
    static constexpr std::string_view mapped_image_sha256="149c1b4510a2dee85eb988d3f6c05785a69cbf50bb8fb751af7d9814a5a6e763";
    struct Declaration {
        std::uint16_t key,source_record_index;
        std::uint32_t source_line,decoded_offset;
        std::string_view resource_key,row_sha256;
        std::uint8_t tooltip_date_flag_byte;
    };
    inline static constexpr std::array<Declaration,147> declarations{{
'''
    for row in rows:
        header+='        {'+','.join([str(row['id']),str(row['source_record_index']),str(row['line']),str(row['decoded_offset']),json.dumps(row['resource_key']),json.dumps(row['row_sha256']),str(row['tooltip_date_flag_byte'])])+'},\n'
    header+='''    }};
    static constexpr const Declaration* lookup(std::uint16_t key) noexcept {
        for(const auto& row:declarations)if(row.key==key)return &row;
        return nullptr;
    }
};
}
'''
    (SERVER/'src/db/NativeBeastSourceCatalog.h').write_text(header,encoding='utf-8')
    print(json.dumps({'source_rows':len(rows),'artifact':str(output),'instances_created':0,'client_execution_tests_builds':False}))


if __name__=='__main__':
    main()
